-- Pagos por cita y crédito de servicios (P3 de odd/tasks/payments-and-receipt.md).
--
-- DECISIONES DE LA DUEÑA (2026-10-10)
--   · Una cita puede tener VARIOS pagos: el abono al reservar y el resto al cobrar
--     (o después), cada uno por su vía: efectivo, transferencia o tarjeta.
--   · Una cita SE PUEDE completar con saldo pendiente: ese saldo queda como CRÉDITO
--     (fiado) de la clienta, para cobrarlo más tarde.
--   · Registrar un pago posterior NUNCA cambia el dinero congelado de la cita
--     (INVARIANTE 2): solo añade filas a `appointment_payment`.
--   · Servicios y productos no se mezclan (INVARIANTE 3): esto es crédito de
--     SERVICIOS. No toca las tablas de crédito de ropa.
--
-- LA TABLA
--   `appointment_payment` es APPEND-ONLY y la única fuente de verdad de lo pagado.
--   Las dueñas solo LEEN (política `select` por membresía); toda escritura entra por
--   las RPC de abajo, que validan estado y sobrepago. Sin política de insert/update/
--   delete y con los privilegios revocados, un cliente no puede saltárselas.
--   kind: 'deposit' (abono antes de cobrar), 'charge' (al cobrar),
--         'credit_payment' (pago posterior de un saldo ya cobrado).
--
-- `appointment.deposit` QUEDA como columna LEGADA de solo lectura: no se borra (los
--   clientes viejos y las suites la siguen escribiendo) pero ya no manda. Lo pagado
--   es la suma de `appointment_payment`; el respaldo de abajo la copió a la tabla.
--
-- VÍA DEL ABONO HISTÓRICO: NULA, no inventada.
--   Los abonos viejos no guardaban cómo se pagaron. Suponer 'cash' falsearía el
--   reporte por vía, así que `method` admite null SOLO en filas `deposit` (check
--   `method is not null or kind = 'deposit'`) y la pantalla muestra "Sin vía
--   registrada". Todo pago nuevo exige vía. `paid_at` del respaldo es el momento
--   del respaldo, no el del pago (se desconoce); los reportes no la usan: atribuyen
--   cada pago a la fecha de su CITA.
--
-- ANTES DE COBRAR NO HAY TOPE: el total solo se congela al completar (el precio
--   puede ser variable o pactado después), así que no hay contra qué comparar.
--   Un abono mayor que el precio se detecta al cobrar: si los pagos nuevos lo
--   pasarían, se rechaza; cobrar SIN pagos nuevos sigue permitido (no se bloquea a
--   la dueña por un abono pasado de largo; devolverlo es asunto de ella).
--
-- ABONO AL AGENDAR: `schedule_appointment` gana el parámetro `p_deposit_method` y
--   crea el pago en la MISMA transacción que la cita (atómico). La firma vieja de 7
--   argumentos se conserva como envoltorio (vía nula) para clientes y suites
--   anteriores.
--
-- COBRAR: `complete_appointment` gana `p_payments jsonb default '[]'` ([{amount,
--   method}]). Como cambia la firma, se elimina la vieja y se crea la nueva; las
--   llamadas de 6 argumentos siguen valiendo por el default.
--
-- ADITIVA salvo el reemplazo de `complete_appointment` (firma nueva).

create table if not exists appointment_payment (
  id             bigint      generated by default as identity primary key,
  business_id    bigint      not null references business (id) on delete cascade,
  appointment_id bigint      not null references appointment (id) on delete cascade,
  amount         bigint      not null check (amount > 0),
  method         text        check (method in ('cash', 'transfer', 'card')),
  kind           text        not null check (kind in ('deposit', 'charge', 'credit_payment')),
  paid_at        timestamptz not null default now(),
  created_by     uuid        default auth.uid(),
  -- La vía solo puede faltar en el abono histórico (ver arriba).
  check (method is not null or kind = 'deposit')
);

create index if not exists appointment_payment_business_idx    on appointment_payment (business_id);
create index if not exists appointment_payment_appointment_idx on appointment_payment (appointment_id);

alter table appointment_payment enable row level security;

do $$
begin
  if not exists (
    select 1 from pg_policies
     where schemaname = 'public' and tablename = 'appointment_payment'
       and policyname = 'appointment_payment_select'
  ) then
    create policy appointment_payment_select on appointment_payment
      for select using (is_member(business_id));
  end if;
end $$;

revoke insert, update, delete on appointment_payment from anon, authenticated;

-- Respaldo: un abono por cita con `deposit > 0`. Idempotente.
insert into appointment_payment (business_id, appointment_id, amount, method, kind)
select a.business_id, a.id, a.deposit, null, 'deposit'
  from appointment a
 where a.deposit > 0
   and not exists (
     select 1 from appointment_payment p where p.appointment_id = a.id and p.kind = 'deposit'
   );

-- ─────────────────────────────────────────────────────────────────────────────
-- Agendar con abono atómico.
-- ─────────────────────────────────────────────────────────────────────────────
create or replace function schedule_appointment(
  p_business_id     bigint,
  p_appointment_id  bigint,
  p_client          text,
  p_datetime        text,
  p_quoted_price    bigint,
  p_deposit         bigint,
  p_service_ids     bigint[],
  p_deposit_method  text
)
returns void language plpgsql security definer
set search_path = public, pg_temp as $$
declare
  v_n        integer;
  v_distinct integer;
  v_valid    integer;
begin
  if auth.uid() is null then raise exception 'No autenticado'; end if;
  if not is_member(p_business_id) then raise exception 'Ese negocio no es tuyo.'; end if;

  if p_client is null or btrim(p_client) = '' then
    raise exception 'Falta el nombre de la clienta.';
  end if;
  if p_datetime is null or btrim(p_datetime) = '' then
    raise exception 'Falta la fecha y hora de la cita.';
  end if;
  if (p_quoted_price is not null and p_quoted_price < 0)
     or (p_deposit is not null and p_deposit < 0) then
    raise exception 'Los montos de la cita no son válidos.';
  end if;
  if p_deposit_method is not null and p_deposit_method not in ('cash', 'transfer', 'card') then
    raise exception 'La vía de pago no es válida.';
  end if;

  if p_service_ids is null or coalesce(array_length(p_service_ids, 1), 0) = 0 then
    raise exception 'Elige al menos un servicio.';
  end if;
  if array_position(p_service_ids, null) is not null then
    raise exception 'Hay un servicio vacío en la lista.';
  end if;

  select count(*), count(distinct s) into v_n, v_distinct from unnest(p_service_ids) as s;
  if v_n <> v_distinct then raise exception 'Un servicio aparece repetido en la cita.'; end if;

  select count(*) into v_valid
    from service
   where business_id = p_business_id
     and id = any (p_service_ids)
     and duration_min > 0;
  if v_valid <> v_n then
    raise exception 'Un servicio no pertenece a tu negocio o no tiene duración.';
  end if;

  insert into appointment (id, business_id, service_id, client, datetime, status,
                           quoted_price, deposit, charged_price, actual_cost, profit)
  values (p_appointment_id, p_business_id, p_service_ids[1], p_client, p_datetime, 'PENDING',
          p_quoted_price, p_deposit, null, null, null);

  insert into appointment_service (appointment_id, service_id, business_id)
  select p_appointment_id, s, p_business_id from unnest(p_service_ids) as s;

  -- El abono es un pago: nace con la cita o no nace ninguno.
  if p_deposit is not null and p_deposit > 0 then
    insert into appointment_payment (business_id, appointment_id, amount, method, kind)
    values (p_business_id, p_appointment_id, p_deposit, p_deposit_method, 'deposit');
  end if;
end $$;

