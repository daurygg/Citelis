-- ─────────────────────────────────────────────────────────────────────────────
-- Cobrar con pagos. Texto actual: 20261010000009_line_discounts.sql. SOLO cambian:
-- la firma (p_payments), la validación de pagos y su inserción.
-- ─────────────────────────────────────────────────────────────────────────────
